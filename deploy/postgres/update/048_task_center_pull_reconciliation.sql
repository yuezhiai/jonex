-- 拉式对账（§4.1 ④，2026-10-11）要加的两列
--
-- 「拉式对账」= 管理方**主动问**运行方「这一步现在什么情况」，不再只等运行方上报
-- （推丢了子任务会挂到编排硬超时，预置 7 小时）。它要在**两侧**各加一列，所以这一个
-- 文件里两条 `ALTER` —— 它们属于**同一个特性**，不要拆成两个编号。
--
-- ⚠️ **一句一个 `ADD COLUMN`** —— 仓库那条「列对齐守卫」只解析单句，
--    写成逗号并列会被它当成没加列。两条各占一句，别合并成一句。
--
-- ⚠️ 两条都带 `IF NOT EXISTS`（幂等）：本文件曾被拆成 048/049 两个号、且旧名是
--    `048_task_center_doc_last_outcome.sql`（那会儿只有第①条）。改名 + 合并之后，
--    在那些环境上重跑都是**空操作** —— 文件名变了会让版本表认不出来、重跑一遍，
--    而重跑是无害的（`already exists, skipping`）。

-- ① 运行方侧（知识库的接管行）：**最后一次收口的那份上报报文**（JSONB）。
--    管理方来问时，运行方靠它答「成功 / 失败 + 产出」。
--
--    ⚠️ 存**整份报文**而不是一个 success/failed 字样（用户 2026-10-11 定：
--    「查询接口的返回应该是上报接口的入参」）：管理方问出「成功了」之后**不能只写状态**，
--    它还要拿这一步的产出（outputs）去填下一步的输入 —— 比如「解析」的产出里有
--    document_id，「编译」那步要用。而产出只有运行方知道。
--    所以把当初要上报的那份报文原样存下、原样回，管理方拿到就当一条上报消化：
--    零转换、不可能分叉。形状见协议层 `StepStatusQuery.report`。
--    NULL = 还没收口，或收口是**中性**的一次（典型：「任务被删除」）。
ALTER TABLE knowledge_base.task_center_documents ADD COLUMN IF NOT EXISTS last_report JSONB;

-- ② 管理方侧（任务中心的子任务）：**对账上一次问过它的时刻**。
--
--    ⚠️ 没有这一列会怎样：`TASK_CENTER_QUERY_QUIET_SEC` 只能当「**第一次**发问」的门槛
--    —— 某步一旦沉默超过它，此后**永远**满足条件，而主循环 3 秒一拍 ⇒ 一个跑几分钟的
--    步骤被问上百次；排序再按 `started_at` 取最老的 N 条时，**最老的那批**（也最可能
--    一直在跑）每拍占满名额，后面新沉默的**永远排不进来**。
--    判据与排序都改成 `COALESCE(last_queried_at, started_at)`：问过就往后排，自然轮转；
--    `_query_one` **无论问到什么都回写**这一列（问到「还在跑」也算问过）。
ALTER TABLE task_center.subtasks ADD COLUMN IF NOT EXISTS last_queried_at TIMESTAMP WITHOUT TIME ZONE;
